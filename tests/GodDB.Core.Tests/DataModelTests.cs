    /// 회원 1:N 주문 모델 (물리명까지 채운 상태)
    private static (DataModel M, Guid Member, Guid Order) Shop()
    {
        var m = new DataModel(name: "shop", kind: DatabaseKind.Mysql);
        var member = m.AddTable(logicalName: "회원");
        var order = m.AddTable(logicalName: "주문");
        m.Tables[0].PhysicalName = "tb_member";
        m.Tables[0].Columns[0].PhysicalName = "id";
        m.Tables[0].Columns[0].LogicalName = "ID";
        m.Tables[0].Columns.Add(new ModelColumn(logicalName: "이메일", physicalName: "email", dataType: "varchar(100)",
                                                notNull: true, unique: true, comment: "로그인 아이디"));
        m.Tables[1].PhysicalName = "tb_order";
        m.Tables[1].Columns[0].PhysicalName = "order_id";
        m.Tables[1].Columns[0].LogicalName = "주문 ID";
        m.Tables[1].Columns.Add(new ModelColumn(logicalName: "주문일시", physicalName: "ordered_at", dataType: "datetime(3)",
                                                notNull: true, defaultValue: "CURRENT_TIMESTAMP(3)"));
        return (m, member, order);
    }

    [Fact]
    public void RelationCopiesParentKeyAsFK()
    {
        var (m, member, order) = Shop();
        var rid = m.AddRelation(member, order);
        Assert.NotNull(rid);
        var child = m.Table(order);
        Assert.NotNull(child);
        var fk = child.Columns[^1];
        Assert.Equal("member_id", fk.PhysicalName);     // id 는 흔한 이름 → 부모테이블_id
        Assert.Equal("회원 ID", fk.LogicalName);
        Assert.Equal("bigint", fk.DataType);
        Assert.False(fk.AutoIncrement);
        Assert.Equal(fk.Id, m.Relations.FirstOrDefault()?.Pairs.FirstOrDefault()?.Child);

        // 삭제하면 FK 컬럼도 지운다
        m.RemoveRelation(rid.Value, dropColumns: true);
        Assert.False(m.Table(order)?.Columns.Any(c => c.Id == fk.Id));
    }

    [Fact]
    public void IdentifyingRelationJoinsPrimaryKey()
    {
        var (m, member, order) = Shop();
        m.AddRelation(member, order, identifying: true);
        var pk = m.Table(order)!.PrimaryKey.Select(c => c.PhysicalName);
        Assert.Equal(["order_id", "member_id"], pk);
    }

    [Fact]
    public void DdlMySQL()
    {
        var (m, member, order) = Shop();
        m.AddRelation(member, order);
        var sql = m.Ddl();
        Assert.Contains("CREATE TABLE `tb_member` (", sql);
        Assert.Contains("`id` bigint NOT NULL auto_increment COMMENT 'ID'", sql);
        Assert.True(sql.Contains("`email` varchar(100) NOT NULL COMMENT '이메일\\n로그인 아이디'")
                    || sql.Contains("COMMENT '이메일\n로그인 아이디'"), sql);
        Assert.Contains("UNIQUE KEY `uk_tb_member_email` (`email`)", sql);
        Assert.Contains("`ordered_at` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)", sql);
        Assert.Contains("COMMENT='회원'", sql);
        Assert.Contains("ALTER TABLE `tb_order` ADD CONSTRAINT `fk_tb_order_tb_member` FOREIGN KEY (`member_id`) REFERENCES `tb_member` (`id`);", sql);
        // FK 는 CREATE 뒤에
        Assert.True(sql.IndexOf("ALTER TABLE", StringComparison.Ordinal) > sql.IndexOf("CREATE TABLE `tb_order`", StringComparison.Ordinal));
    }

