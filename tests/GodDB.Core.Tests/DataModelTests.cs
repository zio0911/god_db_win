    [Fact]
    public void ReverseEngineeringRoundTrip()
    {
        var (m, member, order) = Shop();
        m.AddRelation(member, order);
        var tables = m.PhysicalTables();
        // DB 에서 읽은 것처럼: MySQL 기본값은 따옴표 없이
        tables[1].Columns[1] = tables[1].Columns[1] with { DefaultValue = "CURRENT_TIMESTAMP(3)" };
        var r = DataModel.Reverse(tables, name: "rev", kind: DatabaseKind.Mysql);
        Assert.Equal(2, r.Tables.Count);
        var rm = r.Tables.First(t => t.PhysicalName == "tb_member");
        Assert.Equal("회원", rm.LogicalName);
        var email = rm.Columns.First(c => c.PhysicalName == "email");
        Assert.Equal("이메일", email.LogicalName);
        Assert.Equal("로그인 아이디", email.Comment);
        Assert.True(email.Unique);
        Assert.True(rm.Columns.FirstOrDefault()?.PrimaryKey);
        Assert.True(rm.Columns.FirstOrDefault()?.AutoIncrement);
        Assert.Single(r.Relations);
        Assert.Equal(rm.Id, r.Relations[0].Parent);
        // 다시 DDL 로 뽑아도 같은 결과
        Assert.Contains("REFERENCES `tb_member` (`id`)", r.Ddl());
        // 모델과 DB 비교: 차이 없음
        var report = m.Compare(m.PhysicalTables());
        Assert.Empty(report.Items);
    }

    [Fact]
    public void CommentSplit()
    {
        Assert.Equal("회원", DataModel.CommentText(logical: "회원", physical: "tb_member", comment: ""));
        Assert.Equal("x", DataModel.CommentText(logical: "email", physical: "email", comment: "x"));
        var s = DataModel.SplitComment("회원\n탈퇴 회원 포함");
        Assert.Equal("회원", s.Logical);
        Assert.Equal("탈퇴 회원 포함", s.Comment);
        Assert.Equal("'A'", DataModel.ReverseDefault("A", DatabaseKind.Mysql));
        Assert.Equal("0", DataModel.ReverseDefault("0", DatabaseKind.Mysql));
    }

    [Fact]
    public void StoreRoundTrip()
    {
        var dir = Path.Combine(Path.GetTempPath(), $"goddb-model-{Guid.NewGuid()}");
        try
        {
            var store = new ModelStore(dir);
            var (m, _, _) = Shop();
            store.Save(m);
            var list = store.List();
            Assert.Single(list);
            Assert.True(list[0] == m || list[0].Tables.SequenceEqual(m.Tables));
            store.Delete(m.Id);
            Assert.Empty(store.List());
            Assert.Throws<ModelException>(() => ModelStore.Decode(Encoding.UTF8.GetBytes("{}")));
        }
        finally
        {
            if (Directory.Exists(dir)) Directory.Delete(dir, true);
        }
    }

