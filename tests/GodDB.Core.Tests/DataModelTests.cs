    [Fact]
    public void MacFileDecodesAndReencodesWithSameShape()
    {
        var m = ModelStore.Decode(Encoding.UTF8.GetBytes(MacFile));
        Assert.Equal(Guid.Parse("6F9619FF-8B86-D011-B42D-00C04FC964FF"), m.Id);
        Assert.Equal(DatabaseKind.Postgres, m.Kind);
        Assert.Equal("주문 도메인/초안", m.Memo);
        Assert.Equal(new DateTime(2026, 11, 1, 9, 30, 0, DateTimeKind.Utc), m.Created);
        Assert.Equal("green", m.Tables[0].Color);
        Assert.Null(m.Tables[1].Color);
        Assert.Equal(330.5, m.Tables[0].Y);
        var r = m.Relations[0];
        Assert.Equal(ModelCardinality.OneToMany, r.Cardinality);
        Assert.Equal(ModelFkAction.Cascade, r.OnDelete);
        Assert.Equal(ModelFkAction.SetNull, r.OnUpdate);
        Assert.True(r.Identifying);

        var again = ModelStore.Encode(m);
        using var a = JsonDocument.Parse(MacFile);
        using var b = JsonDocument.Parse(again);
        AssertSameJson(a.RootElement, b.RootElement, "$");
        // 키 순서도 Swift sortedKeys 와 같다
        Assert.Equal(a.RootElement.EnumerateObject().Select(p => p.Name), b.RootElement.EnumerateObject().Select(p => p.Name));
        // UUID 는 대문자, 날짜는 초 단위 ISO 8601
        var text = Encoding.UTF8.GetString(again);
        Assert.Contains("\"6F9619FF-8B86-D011-B42D-00C04FC964FF\"", text);
        Assert.Contains("\"2026-11-02T10:00:05Z\"", text);
        Assert.Equal(m, ModelStore.Decode(again));
    }

    [Fact]
    public void OldRelationWithoutOptionalKeysGetsDefaults()
    {
        var json = MacFile.Replace("""
                  "createConstraint" : true,
            """, "").Replace("""
                  "onDelete" : "CASCADE",
                  "onUpdate" : "SET NULL",
                  "optional" : false,
            """, "");
        Assert.DoesNotContain("onDelete", json);
        var m = ModelStore.Decode(Encoding.UTF8.GetBytes(json));
        Assert.True(m.Relations[0].CreateConstraint);
        Assert.Equal(ModelFkAction.NoAction, m.Relations[0].OnDelete);
        // 테이블의 필수 키가 빠지면 Mac 처럼 모델 파일이 아니다
        Assert.Throws<ModelException>(() => ModelStore.Decode(Encoding.UTF8.GetBytes(MacFile.Replace("\"memo\" :", "\"memo2\" :"))));
        Assert.Throws<ModelException>(() => ModelStore.Decode(Encoding.UTF8.GetBytes(MacFile.Replace("goddb-model", "other"))));
        Assert.Throws<ModelException>(() => ModelStore.Decode(Encoding.UTF8.GetBytes(MacFile.Replace("\"1:N\"", "\"N:M\""))));
    }

    private static void AssertSameJson(JsonElement a, JsonElement b, string path)
    {
        Assert.True(a.ValueKind == b.ValueKind, $"{path}: {a.ValueKind} != {b.ValueKind}");
        switch (a.ValueKind)
        {
            case JsonValueKind.Object:
                Assert.Equal(a.EnumerateObject().Select(p => p.Name).Order(StringComparer.Ordinal),
                             b.EnumerateObject().Select(p => p.Name).Order(StringComparer.Ordinal));
                foreach (var p in a.EnumerateObject()) AssertSameJson(p.Value, b.GetProperty(p.Name), $"{path}.{p.Name}");
                break;
            case JsonValueKind.Array:
                Assert.Equal(a.GetArrayLength(), b.GetArrayLength());
                for (int i = 0; i < a.GetArrayLength(); i++) AssertSameJson(a[i], b[i], $"{path}[{i}]");
                break;
            case JsonValueKind.Number:
                Assert.Equal(a.GetDouble(), b.GetDouble());
                break;
            case JsonValueKind.String:
                Assert.Equal(a.GetString(), b.GetString());
                break;
        }
    }

    [Fact]
    public void WorkspaceUndoDuplicateRenameImportExport()
    {
        var dir = Path.Combine(Path.GetTempPath(), $"goddb-ws-{Guid.NewGuid()}");
        try
        {
            var ws = new ModelWorkspace(new ModelStore(Path.Combine(dir, "models")));
            ws.LoadIfNeeded();
            Assert.Empty(ws.Models);
            var m = ws.Create(DatabaseKind.Redis);
            Assert.Equal(DatabaseKind.Mysql, m.Kind);
            Assert.Equal("새 모델 1", m.Name);
            Assert.Equal("회원", m.Tables[0].LogicalName);
            Assert.Equal(m.Id, ws.SelectedId);

            Assert.False(ws.CanUndo(m.Id));
            ws.Edit(m.Id, x => x.AddTable(logicalName: "주문"));
            Assert.Equal(2, ws.Find(m.Id)!.Tables.Count);
            Assert.True(ws.CanUndo(m.Id));
            ws.UndoLast(m.Id);
            Assert.Single(ws.Find(m.Id)!.Tables);
            Assert.False(ws.CanUndo(m.Id));

            ws.Rename(m.Id, "  shop  ");
            Assert.Equal("shop", ws.Find(m.Id)!.Name);
            ws.Rename(m.Id, "   ");
            Assert.Equal("shop", ws.Find(m.Id)!.Name);
            Assert.False(ws.CanUndo(m.Id));

            var copy = ws.Duplicate(m.Id)!;
            Assert.NotEqual(m.Id, copy.Id);
            Assert.Equal("shop 복사본", copy.Name);
            Assert.Equal(copy.Id, ws.SelectedId);

            var file = Path.Combine(dir, ModelWorkspace.ExportFileName(ws.Find(m.Id)!));
            ws.ExportFile(m.Id, file);
            var bad = Path.Combine(dir, "bad.goddbmodel");
            File.WriteAllText(bad, "{}");
            var failed = ws.ImportFiles([file, bad]);
            Assert.Single(failed);
            Assert.Equal("GodDB 모델 파일이 아니에요.", failed[0].Error);
            // 같은 id 를 가져오면 새 id 로
            Assert.Equal(3, ws.Models.Count);
            Assert.Equal(3, ws.Models.Select(x => x.Id).Distinct().Count());

            ws.FlushSaves();
            var reload = new ModelWorkspace(new ModelStore(Path.Combine(dir, "models")));
            reload.LoadIfNeeded();
            Assert.Equal(3, reload.Models.Count);
            Assert.Contains(reload.Models, x => x.Id == m.Id && x.Name == "shop");

            ws.Delete(copy.Id);
            Assert.Equal(2, ws.Models.Count);
            Assert.NotEqual(copy.Id, ws.SelectedId);
            Assert.False(File.Exists(Path.Combine(dir, "models", copy.Id.ToString().ToUpperInvariant() + ".goddbmodel")));
        }
        finally
        {
            if (Directory.Exists(dir)) Directory.Delete(dir, true);
        }
    }

    [Fact]
    public void SampleAndDiagramHelpers()
    {
        var m = ModelingSample.Model();
        Assert.Equal(4, m.Tables.Count);
        Assert.Equal(3, m.Relations.Count);
        // 가입일시 물리명이 비어 있어 검사 오류
        Assert.Contains(m.Issues(), i => i.Level == ModelIssueLevel.Error);
        var item = m.Tables.First(t => t.PhysicalName == "tb_order_item");
        Assert.Equal(["id", "order_id"], item.PrimaryKey.Select(c => c.PhysicalName));
        Assert.Contains(item.Columns, c => c.PhysicalName == "product_id");

        var rel = m.Relations[0];
        var g = ModelDiagram.Geometry(m, rel);
        Assert.NotNull(g);
        // 자식(주문, 오른쪽) → 부모(회원, 왼쪽): 자식 왼쪽 끝에서 부모 오른쪽 끝으로
        Assert.Equal(380, g.Value.Start.X);
        Assert.Equal(40 + ModelDiagram.CardWidth, g.Value.End.X);
        Assert.NotNull(ModelDiagram.Midpoint(m, rel));
        Assert.Equal("● 1:N", ModelDiagram.RelationBadge(m.Relations[1]));
        Assert.Equal("회원 → 주문 · 1:N · 비식별", ModelDiagram.RelationHelp(m, rel));
        Assert.Equal(("이메일", (string?)"email", false), ModelDiagram.Label("이메일", "email", ModelNameMode.Both));
        Assert.Equal(("가입일시", (string?)"물리명 없음", true), ModelDiagram.Label("가입일시", "", ModelNameMode.Both));
        Assert.Equal("%@ 관계 · 먼저 부모(참조되는) 테이블을 누르세요".Replace("%@", "식별 1:N"),
                     ModelDiagram.ToolHint(m, new ModelTool.Relation(ModelCardinality.OneToMany, true), null));
        Assert.Equal(ModelTool.SelectTool, ModelTool.Toggle(ModelTool.AddTableTool, new ModelTool.AddTable()));

        ModelDiagram.AutoLayout(m);
        var member = m.Tables.First(t => t.PhysicalName == "tb_member");
        var order = m.Tables.First(t => t.PhysicalName == "tb_order");
        Assert.True(member.X < order.X && order.X < item.X);
        Assert.Contains("bigint", DataModel.CommonTypes(DatabaseKind.Postgres));
    }
