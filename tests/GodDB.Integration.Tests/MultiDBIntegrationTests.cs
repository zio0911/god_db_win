/// Mac MultiDBChecks (MultiDBIntegrationTests.swift + PagingTests / DiagramTests / ResultEditingTests 의 확장)
internal static partial class MultiDBChecks
{
    [GeneratedRegex(@"^\d{4}-\d{2}-\d{2} \d{2}:\d{2}")] private static partial Regex DateTimeHead();

    public static async Task Run(DatabaseKind kind)
    {
        TestDb.Port(kind); // 환경변수가 없으면 건너뛴다
        await using var scratch = await MultiDbScratch.SeedAsync(kind);
        var s = scratch.Session;
        var d = s.Dialect;
        var c = scratch.Container;

        // 연결 테스트용 서버 버전
        var version = await s.ServerVersionAsync();
        Assert.True(version.StartsWith(kind.Title()) && version.Length > kind.Title().Length + 2, version);

        // DB/스키마 목록
        var dbs = await s.DatabasesAsync();
        Assert.True(dbs.Contains(c), string.Join(",", dbs));

        // 쿼리 + 자동 LIMIT/TOP + NULL + 한글
        var r = await s.ExecuteAsync("SELECT member_id, email FROM tb_member ORDER BY member_id", limit: 2);
        Assert.Equal(["member_id", "email"], r.Columns.Select(x => x.Name.ToLowerInvariant()));
        Assert.Equal(2, r.Rows.Count);
        Assert.Equal("이@샘플.com", r.Rows[1].Values[1]);
        var nulls = await s.ExecuteAsync("SELECT email FROM tb_member WHERE email IS NULL", limit: 500);
        Assert.NotEmpty(nulls.Rows);
        Assert.Null(nulls.Rows[0].Values[0]);

        // 페이징
        await Paging(s, "tb_member");
        await ServerSort(s, "tb_member");
        await RenameAndDrop(s, c);
        // editing: 결과 편집(ResultEditing) 미포팅 — 건너뜀
        await Binary(s, c);
        await ForeignKeys(s, c);

        // 날짜 형식
        var dt = await s.ExecuteAsync("SELECT reg_dt FROM tb_member ORDER BY member_id", limit: 1);
        var dtv = dt.Rows.FirstOrDefault()?.Values[0];
        Assert.True(dtv != null && DateTimeHead().IsMatch(dtv), dtv);

        // 스키마
        var tables = await s.LoadSchemaAsync(c);
        var member = Assert.Single(tables, t => t.Name == "tb_member");
        Assert.Equal("회원", member.Comment);
        Assert.Equal(["member_id", "email", "status", "reg_dt"], member.Columns.Select(x => x.Name));
        Assert.True(member.Columns[0].IsPrimaryKey);
        Assert.Contains("identity", member.Columns[0].Extra);
        Assert.NotNull(member.Columns[2].DefaultValue);
        Assert.Contains(member.Indexes, i => i.IsPrimary && i.Columns.SequenceEqual(["member_id"]));
        Assert.Contains(member.Indexes, i => i.Name == "idx_email" && !i.IsConstraint);
        var coupon = Assert.Single(tables, t => t.Name == "tb_coupon");
        Assert.Contains(coupon.Indexes, i => i.Unique && i.IsConstraint && !i.IsPrimary);

        // 뷰/함수/프로시저 정의
        var routines = await s.LoadRoutinesAsync(c);
        var view = Assert.Single(routines, x => x.Kind == RoutineKind.View && x.Name == "v_member");
        Assert.Contains("member_id", (await s.DefinitionAsync(view))?.ToLowerInvariant() ?? "");
        if (kind == DatabaseKind.Postgres)
        {
            var fn = Assert.Single(routines, x => x.Kind == RoutineKind.Function && x.Name == "fn_count");
            Assert.Contains("count(*)", await s.DefinitionAsync(fn) ?? "");
        }
        else
        {
            var sp = Assert.Single(routines, x => x.Kind == RoutineKind.Procedure && x.Name == "sp_count");
            Assert.Contains("COUNT(*)", await s.DefinitionAsync(sp) ?? "");
        }

        // 실행 계획
        var (plan, tree) = await s.ExplainAsync("SELECT * FROM tb_member WHERE status = 'A'");
        Assert.NotEmpty(plan.Rows);
        Assert.False(string.IsNullOrEmpty(tree));
        Assert.True(PlanAnalyzer.Warnings(plan).Any(w => w.Message.Contains("스캔") || w.Message.Contains("Scan")),
            string.Join("\n", plan.Rows.Select(x => string.Join(" | ", x.Values))));
        // 실행 계획 뒤에도 일반 쿼리가 정상 실행돼야 한다 (SHOWPLAN OFF 확인)
        Assert.Equal("3", (await s.ExecuteAsync("SELECT COUNT(*) FROM tb_member", limit: 0)).Rows.FirstOrDefault()?.Values[0]);

        // DDL 생성 → 그대로 실행 가능해야 한다
        var ddl = await s.TableDdlAsync(coupon);
        await s.RawAsync(ddl.Replace(d.QuoteTable("tb_coupon"), d.QuoteTable("tb_coupon_copy"))
            .Replace("pk_coupon", "pk_coupon_copy")
            .Replace("uq_coupon_code", "uq_coupon_code_copy")
            .Replace("tb_coupon_pkey", "tb_coupon_copy_pkey")
            .Replace("tb_coupon_code_key", "tb_coupon_copy_code_key"));
        await s.RawAsync($"DROP TABLE {d.QuoteTable("tb_coupon_copy")}");

        // 테이블 수정 (ALTER) → 실제 실행 후 결과 확인
        await s.RawAsync("CREATE TABLE tb_alter_it (id int PRIMARY KEY, email varchar(100), nick varchar(20))");
        await s.RawAsync("CREATE INDEX idx_alter_email ON tb_alter_it (email)");
        var original = Assert.Single(await s.LoadSchemaAsync(c), t => t.Name == "tb_alter_it");
        var cols = original.Columns.Select(x => new EditableColumn(x)).ToList();
        cols[1].Name = "mail";
        cols[1].ColumnType = "varchar(200)";
        cols.RemoveAt(2);
        cols.Add(new EditableColumn(name: "status", columnType: "char(1)", nullable: false,
                                    defaultValue: kind == DatabaseKind.Postgres ? "'A'" : "('A')", comment: "상태"));
        var idx = original.Indexes.Select(x => new EditableIndex(x)).ToList();
        foreach (var x in idx) if (x.Name == "idx_alter_email") x.Columns = ["mail"];
        var alter = TableAlter.Statement(original, cols, idx, "테스트", d);
        Assert.NotNull(alter);
        await s.RawAsync(alter);
        var after = Assert.Single(await s.LoadSchemaAsync(c), t => t.Name == "tb_alter_it");
        Assert.True(after.Columns.Select(x => x.Name).SequenceEqual(["id", "mail", "status"]), alter);
        Assert.Contains("200", after.Columns[1].ColumnType);
        Assert.Equal("상태", after.Columns[^1].Comment);
        Assert.Equal(["mail"], after.Indexes.First(i => i.Name == "idx_alter_email").Columns);
        Assert.Equal("테스트", after.Comment);

        // 스키마 비교 → 보정 SQL 적용 → 차이 없음
        string[] compared = ["tb_member", "tb_coupon"];
        var source = (await s.LoadSchemaAsync(c)).Where(t => compared.Contains(t.Name)).ToList();
        var targetName = scratch.Target;
        var target = await s.LoadSchemaAsync(targetName);
        var report = SchemaDiff.Compare(source, target, dialect: d);
        Assert.Contains(report.Items, i => i.Kind == SchemaDiffKind.MissingTable && i.Table == "tb_coupon");
        Assert.Contains(report.Items, i => i.Kind == SchemaDiffKind.DifferentColumn && i.Object == "email");
        Assert.Contains(report.Items, i => i.Kind == SchemaDiffKind.MissingColumn && i.Object == "reg_dt");
        Assert.Contains(report.Items, i => i.Kind == SchemaDiffKind.MissingIndex && i.Object == "idx_email");
        await s.UseAsync(targetName);
        var failures = new List<string>();
        foreach (var item in report.Items)
        {
            if (item.FixSql is not { } fix) continue;
            try { await s.RawAsync(fix); }
            catch (Exception e) { failures.Add($"보정 SQL 실패 ({item.Id}): {fix}\n{e.Message}"); }
        }
        Assert.True(failures.Count == 0, string.Join("\n", failures));
        var synced = (await s.LoadSchemaAsync(targetName)).Where(t => compared.Contains(t.Name)).ToList();
        var again = SchemaDiff.Compare(source, synced, dialect: d)
            .Items.Where(i => i.Severity != SchemaDiffSeverity.Extra && !(i.Kind == SchemaDiffKind.DifferentColumn && i.Object == "member_id")).ToList();
        Assert.True(again.Count == 0, string.Join("; ", again.Select(i => $"{i.Table}.{i.Object ?? ""}: {i.Detail}")));
        await s.UseAsync(c);

        // 읽기전용
        var ro = s.Profile with { ReadOnly = true };
        var (_, pw) = It.Multi(kind, scratch.Database);
        await using (var rs = await DbSession.ConnectAsync(ro, pw))
        {
            var blocked = await Assert.ThrowsAsync<GodDbException>(() => rs.ExecuteAsync("DELETE FROM tb_member", limit: 0));
            Assert.Equal(DbErrorKind.ReadOnlyRejected, blocked.Kind);
            if (kind == DatabaseKind.Postgres)
                // Mac 은 기본 스키마(public)의 tb_member — 여기서는 테스트 스키마를 직접 적는다
                await Assert.ThrowsAnyAsync<Exception>(() => rs.RawAsync($"INSERT INTO {c}.tb_member (email) VALUES ('x')"));
        }

        // 비밀번호 오류 → 인증 실패로 인식 (ErrorText.isAuthFailure 는 미포팅 — 연결 실패만 확인)
        var bad = s.Profile with { ReadOnly = false };
        await Assert.ThrowsAnyAsync<Exception>(() => DbSession.ConnectAsync(bad, "wrong-password"));
    }

    /// 세 DB 공통: 페이지 이동과 전체 행 수 (Mac PagingTests.swift)
    public static async Task Paging(DbSession s, string table)
    {
        var sql = $"SELECT member_id FROM {s.Dialect.QuoteTable(table)} ORDER BY member_id";
        var p0 = await s.ExecuteAsync(sql, limit: 2, page: 0);
        Assert.True(p0.Rows.Count == 2 && p0.HasMore && p0.Page == 0 && p0.PageSize == 2);
        var p1 = await s.ExecuteAsync(sql, limit: 2, page: 1);
        Assert.True(p1.Rows.Count == 1 && !p1.HasMore);
        Assert.Equal(["1", "2", "3"], p0.Rows.Select(x => x.Values[0]).Concat(p1.Rows.Select(x => x.Values[0])));
        // ORDER BY 없는 쿼리도 (SQL Server 는 TOP + 앞부분 버리기)
        var noOrder = await s.ExecuteAsync($"SELECT member_id FROM {s.Dialect.QuoteTable(table)}", limit: 2, page: 1);
        Assert.Single(noOrder.Rows);
        Assert.Equal(3, await s.CountAsync(sql));
    }

    /// 세 DB 공통: 테이블 이름 변경 후 삭제 (Mac PagingTests.swift)
    public static async Task RenameAndDrop(DbSession s, string container)
    {
        var d = s.Dialect;
        // 이전 실행이 중간에 멈춰 남은 테이블 정리
        foreach (var t in new[] { "tb_rename_it", "tb_renamed_it" }) { try { await s.RawAsync(d.DropTableSql(t)); } catch { } }
        await s.RawAsync("CREATE TABLE tb_rename_it (id int PRIMARY KEY)");
        await s.RawAsync(d.RenameTableSql("tb_rename_it", "tb_renamed_it"));
        var names = (await s.LoadSchemaAsync(container)).Select(t => t.Name).ToList();
        Assert.True(names.Contains("tb_renamed_it") && !names.Contains("tb_rename_it"));
        await s.RawAsync(d.DropTableSql("tb_renamed_it"));
        names = (await s.LoadSchemaAsync(container)).Select(t => t.Name).ToList();
        Assert.DoesNotContain("tb_renamed_it", names);
    }

    /// 세 DB 공통: DB 에서 정렬 + 페이징 유지 (Mac PagingTests.swift)
    public static async Task ServerSort(DbSession s, string table)
    {
        var sql = $"SELECT member_id, email FROM {s.Dialect.QuoteTable(table)} ORDER BY member_id";
        var desc = new ResultSort("member_id", false);
        var p0 = await s.ExecuteAsync(sql, limit: 2, page: 0, sort: desc);
        Assert.Equal(["3", "2"], p0.Rows.Select(x => x.Values[0]));
        Assert.True(p0.ServerSort == desc && p0.HasMore);
        var p1 = await s.ExecuteAsync(sql, limit: 2, page: 1, sort: desc);
        Assert.Equal(["1"], p1.Rows.Select(x => x.Values[0]));
    }

    /// 세 DB 공통: 바이너리 컬럼이 0x16진수로 보인다 (Mac ResultEditingTests.swift).
    /// 편집으로 바이너리 값을 저장하는 뒷부분은 결과 편집(ResultEditing) 미포팅이라 건너뛴다.
    /// binaryLiteral 도 아직 없어서 Mac MySQLDialect/PostgresDialect/MSSQLDialect.binaryLiteral 과 같은 리터럴을 직접 쓴다.
    public static async Task Binary(DbSession s, string container)
    {
        var d = s.Dialect;
        var type = d.Kind == DatabaseKind.Postgres ? "bytea" : "varbinary(16)";
        var literal = d.Kind switch
        {
            DatabaseKind.Postgres => "decode('CD01FF00', 'hex')",
            DatabaseKind.Mssql => "0xCD01FF00",
            _ => "X'CD01FF00'",
        };
        try { await s.RawAsync(d.DropTableSql("tb_bin_it")); } catch { }
        await s.RawAsync($"CREATE TABLE tb_bin_it (id int PRIMARY KEY, data {type} NULL)");
        await s.RawAsync($"INSERT INTO tb_bin_it (id, data) VALUES (1, {literal})");
        var r = await s.ExecuteAsync("SELECT id, data FROM tb_bin_it", limit: 500);
        Assert.Equal("0xCD01FF00", r.Rows.FirstOrDefault()?.Values[1]);
        await s.RawAsync(d.DropTableSql("tb_bin_it"));
    }

    /// 세 DB 공통: 외래 키를 읽는다 (여러 컬럼 포함) (Mac DiagramTests.swift)
    public static async Task ForeignKeys(DbSession s, string container)
    {
        var d = s.Dialect;
        try { await s.RawAsync(d.DropTableSql("tb_fk_child")); } catch { }
        try { await s.RawAsync(d.DropTableSql("tb_fk_parent")); } catch { }
        await s.RawAsync("CREATE TABLE tb_fk_parent (a int NOT NULL, b int NOT NULL, PRIMARY KEY (a, b))");
        await s.RawAsync("""
            CREATE TABLE tb_fk_child (id int PRIMARY KEY, pa int NULL, pb int NULL,
              CONSTRAINT fk_child_parent FOREIGN KEY (pa, pb) REFERENCES tb_fk_parent (a, b))
            """);
        var tables = await s.LoadSchemaAsync(container);
        var child = Assert.Single(tables, t => t.Name == "tb_fk_child");
        Assert.NotEmpty(child.ForeignKeys);
        var fk = child.ForeignKeys[0];
        Assert.Equal("fk_child_parent", fk.Name);
        Assert.Equal("tb_fk_parent", fk.ReferencedTable);
        Assert.True(fk.Columns.SequenceEqual(["pa", "pb"]) && fk.ReferencedColumns.SequenceEqual(["a", "b"]));
        Assert.Contains("tb_fk_child", DiagramLayout.Related("tb_fk_parent", tables).Select(t => t.Name));
        await s.RawAsync(d.DropTableSql("tb_fk_child"));
        await s.RawAsync(d.DropTableSql("tb_fk_parent"));
    }
