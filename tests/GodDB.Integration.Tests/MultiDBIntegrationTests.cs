/// Mac MultiDBIntegrationTests.swift — PostgreSQL / SQL Server 실제 서버 통합 테스트.
/// Mac 은 public / shop · stg / shop_stg 를 매번 지우고 다시 만들지만, 여기서는 다른 테스트와 겹치지 않게
/// 실행마다 새 스키마(PostgreSQL) · 새 DB(SQL Server) 를 만들어 쓰고 끝나면 지운다. 테이블 이름은 Mac 과 같다.
internal sealed class MultiDbScratch : IAsyncDisposable
{
    public required DbSession Session { get; init; }
    public required DatabaseKind Kind { get; init; }
    /// 테스트 대상 컨테이너 (Mac: public / shop)
    public required string Container { get; init; }
    /// 스키마 비교 대상 (Mac: stg / shop_stg)
    public required string Target { get; init; }
    /// 접속 정보의 database (PostgreSQL 은 shop, SQL Server 는 Container)
    public required string Database { get; init; }

    /// Mac MultiDB.seed
    public static async Task<MultiDbScratch> SeedAsync(DatabaseKind kind)
    {
        var sfx = It.Suffix();
        if (kind == DatabaseKind.Postgres)
        {
            string c = $"it_{sfx}", t = $"stg_{sfx}";
            var s = await It.ConnectAsync(kind, "shop");
            var scratch = new MultiDbScratch { Session = s, Kind = kind, Container = c, Target = t, Database = "shop" };
            try
            {
                string[] sql =
                [
                    $"CREATE SCHEMA {c}", $"CREATE SCHEMA {t}", $"SET search_path TO {c}",
                    """
                    CREATE TABLE tb_member (member_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      email varchar(100), status char(1) NOT NULL DEFAULT 'A', reg_dt timestamp NOT NULL DEFAULT now())
                    """,
                    "CREATE INDEX idx_email ON tb_member (email)",
                    "COMMENT ON TABLE tb_member IS '회원'", "COMMENT ON COLUMN tb_member.email IS '메일'",
                    "CREATE TABLE tb_coupon (id int PRIMARY KEY, code varchar(20) NOT NULL UNIQUE)",
                    "INSERT INTO tb_member (email) VALUES ('kim@sample.com'), ('이@샘플.com'), (NULL)",
                    "CREATE OR REPLACE VIEW v_member AS SELECT member_id, email FROM tb_member",
                    "CREATE OR REPLACE FUNCTION fn_count() RETURNS bigint LANGUAGE sql AS $$ SELECT count(*) FROM tb_member $$",
                    $"CREATE TABLE {t}.tb_member (member_id bigint PRIMARY KEY, email varchar(50), status char(1) NOT NULL DEFAULT 'A')",
                ];
                foreach (var q in sql) await s.RawAsync(q);
                await s.UseAsync(c);
                return scratch;
            }
            catch { await scratch.DisposeAsync(); throw; }
        }
        else
        {
            string c = $"goddb_it_{sfx}", t = $"goddb_it_stg_{sfx}";
            await using (var admin = await It.ConnectAsync(kind, "master"))
            {
                await admin.RawAsync($"CREATE DATABASE {c}");
                await admin.RawAsync($"CREATE DATABASE {t}");
            }
            var s = await It.ConnectAsync(kind, c);
            var scratch = new MultiDbScratch { Session = s, Kind = kind, Container = c, Target = t, Database = c };
            try
            {
                string[] sql =
                [
                    $"USE {c}",
                    """
                    CREATE TABLE tb_member (member_id bigint IDENTITY(1,1) CONSTRAINT pk_member PRIMARY KEY,
                      email nvarchar(100) NULL, status char(1) NOT NULL DEFAULT ('A'),
                      reg_dt datetime2(3) NOT NULL DEFAULT (sysdatetime()))
                    """,
                    "CREATE INDEX idx_email ON tb_member (email)",
                    "EXEC sys.sp_addextendedproperty @name=N'MS_Description', @value=N'회원', @level0type=N'SCHEMA', @level0name=N'dbo', @level1type=N'TABLE', @level1name=N'tb_member'",
                    "CREATE TABLE tb_coupon (id int CONSTRAINT pk_coupon PRIMARY KEY, code varchar(20) NOT NULL CONSTRAINT uq_coupon_code UNIQUE)",
                    "INSERT INTO tb_member (email) VALUES (N'kim@sample.com'), (N'이@샘플.com'), (NULL)",
                    "EXEC('CREATE VIEW v_member AS SELECT member_id, email FROM tb_member')",
                    "EXEC('CREATE PROCEDURE sp_count AS SELECT COUNT(*) AS cnt FROM tb_member')",
                    $"USE {t}",
                    "CREATE TABLE tb_member (member_id bigint CONSTRAINT pk_member_stg PRIMARY KEY, email nvarchar(50) NULL, status char(1) NOT NULL DEFAULT ('A'))",
                    $"USE {c}",
                ];
                foreach (var q in sql) await s.RawAsync(q);
                await s.UseAsync(c);
                return scratch;
            }
            catch { await scratch.DisposeAsync(); throw; }
        }
    }

    public async ValueTask DisposeAsync()
    {
        await Session.CloseAsync();
        if (Kind == DatabaseKind.Postgres)
            await It.CleanupAsync(Kind, "shop", $"DROP SCHEMA IF EXISTS {Container} CASCADE", $"DROP SCHEMA IF EXISTS {Target} CASCADE");
        else
            await It.CleanupAsync(Kind, "master", [.. It.DropMssqlDatabase(Container), .. It.DropMssqlDatabase(Target)]);
    }
}

public class PostgresIntegrationTests
{
    [Fact] public Task Everything() => MultiDBChecks.Run(DatabaseKind.Postgres);
}

